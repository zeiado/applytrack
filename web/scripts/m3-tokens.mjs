// Generates Sekka's colour roles from the brand teal with Material 3's colour system
// (docs/adr/0013-material-3-design-tokens.md). Run `npm run tokens` after changing SEED.
//
// Writes:
//   src/app/m3-tokens.css  the :root and .dark variables that globals.css imports
//   brand/tokens.json      the same colours with their contrast ratios, for designers
//
// Fails without writing anything if a text colour drops below WCAG AA (4.5:1), or a
// border or focus ring below 3:1.

import { writeFileSync } from "node:fs";

import {
  argbFromHex,
  Hct,
  hexFromArgb,
  MaterialDynamicColors as M,
  SchemeTonalSpot,
} from "@material/material-color-utilities";

const SEED = "#00695A"; // Sekka teal

/** shadcn variable → Material role, per mode. Cards sit one step off the page surface. */
const ROLES = {
  background: "surface",
  foreground: "onSurface",
  card: { light: "surfaceContainerLowest", dark: "surfaceContainerLow" },
  "card-foreground": "onSurface",
  popover: "surfaceContainer",
  "popover-foreground": "onSurface",
  primary: "primary",
  "primary-foreground": "onPrimary",
  "primary-container": "primaryContainer",
  "primary-container-foreground": "onPrimaryContainer",
  secondary: "secondaryContainer",
  "secondary-foreground": "onSecondaryContainer",
  muted: "surfaceContainerHigh",
  "muted-foreground": "onSurfaceVariant",
  accent: "secondaryContainer",
  "accent-foreground": "onSecondaryContainer",
  destructive: "error",
  border: "outlineVariant",
  input: "outline",
  ring: "primary",
  "chart-1": "primary",
  "surface-container-lowest": "surfaceContainerLowest",
  "surface-container-low": "surfaceContainerLow",
  "surface-container": "surfaceContainer",
  "surface-container-high": "surfaceContainerHigh",
  "surface-container-highest": "surfaceContainerHighest",
  sidebar: "surfaceContainerLow",
  "sidebar-foreground": "onSurface",
  "sidebar-primary": "primary",
  "sidebar-primary-foreground": "onPrimary",
  "sidebar-accent": "secondaryContainer",
  "sidebar-accent-foreground": "onSecondaryContainer",
  "sidebar-border": "outlineVariant",
  "sidebar-ring": "primary",
};

/** [text, background, minimum ratio]: every pair the app puts on screen. */
const PAIRS = [
  ["foreground", "background", 4.5],
  ["foreground", "card", 4.5],
  ["foreground", "popover", 4.5],
  ["foreground", "muted", 4.5],
  ["muted-foreground", "background", 4.5],
  ["muted-foreground", "card", 4.5],
  ["muted-foreground", "muted", 4.5],
  ["primary", "background", 4.5],
  ["primary", "card", 4.5],
  ["primary-foreground", "primary", 4.5],
  ["primary-container-foreground", "primary-container", 4.5],
  ["secondary-foreground", "secondary", 4.5],
  ["destructive", "background", 4.5],
  ["destructive", "card", 4.5],
  ["input", "background", 3],
  ["input", "card", 3],
  ["ring", "background", 3],
];

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const source = Hct.fromInt(argbFromHex(SEED));
const modes = {};
const failures = [];
for (const mode of ["light", "dark"]) {
  const scheme = new SchemeTonalSpot(source, mode === "dark", 0);
  modes[mode] = Object.fromEntries(
    Object.entries(ROLES).map(([name, role]) => {
      const key = typeof role === "string" ? role : role[mode];
      return [name, hexFromArgb(M[key].getArgb(scheme)).toUpperCase()];
    }),
  );
  for (const [text, background, min] of PAIRS) {
    const ratio = contrast(modes[mode][text], modes[mode][background]);
    if (ratio < min) failures.push(`${mode}: ${text} on ${background} is ${ratio.toFixed(2)}:1, needs ${min}:1`);
  }
}
if (failures.length) {
  console.error(failures.join("\n"));
  process.exit(1);
}

const block = (selector, colours) =>
  `${selector} {\n${Object.entries(colours)
    .map(([name, hex]) => `  --${name}: ${hex};`)
    .join("\n")}\n}\n`;

writeFileSync(
  new URL("../src/app/m3-tokens.css", import.meta.url),
  `/* Generated by scripts/m3-tokens.mjs from ${SEED} (Material 3, tonal spot). Don't edit by hand:
 * change the script and run \`npm run tokens\`. Brand amber and the status colours live in
 * globals.css. */\n\n${block(":root", modes.light)}\n${block(".dark", modes.dark)}`,
);

const json = {
  seed: SEED,
  scheme: "Material 3 tonal spot",
  colours: modes,
  contrast: Object.fromEntries(
    ["light", "dark"].map((mode) => [
      mode,
      Object.fromEntries(
        PAIRS.map(([text, background]) => [
          `${text} on ${background}`,
          Number(contrast(modes[mode][text], modes[mode][background]).toFixed(2)),
        ]),
      ),
    ]),
  ),
};
writeFileSync(new URL("../brand/tokens.json", import.meta.url), `${JSON.stringify(json, null, 2)}\n`);

console.log("Wrote src/app/m3-tokens.css and brand/tokens.json");
